// Regenerates utils/academyExamples.ts for techniques that don't have an example yet:
//   HARVEST=1 pnpm test academyHarvest
// Each example is a real solver state where the technique is the next logical move. Existing
// examples are kept as they are, so the Academy only changes where a technique is new.
import { writeFileSync } from "node:fs";
import { describe, expect, it } from "vitest";

import type { TechniqueId } from "../utils/sudokuGrader";

import { ACADEMY_EXAMPLES, type AcademyExample } from "../utils/academyExamples";
import { generatePuzzle, getGridCandidates, makeRng } from "../utils/sudokuCore";
import { nextHint, type DigitAt } from "../utils/sudokuGrader";

const WANTED: TechniqueId[] = [
  "skyscraper",
  "two-string-kite",
  "unique-rectangle",
  "simple-coloring",
  "finned-x-wing",
  "w-wing",
  "bug-plus-one",
  "empty-rectangle",
];

function harvest(technique: TechniqueId): AcademyExample | null {
  for (let seed = 1; seed <= 2000; seed++) {
    const board = generatePuzzle(62, makeRng(seed)).puzzle.map((r) => [...r]);
    const elims: DigitAt[] = [];
    for (let step = 0; step < 600; step++) {
      const move = nextHint(board, elims);
      if (!move) break;
      if (move.technique === technique) {
        // Pencil marks for the pattern and the cells it clears or fills, as the solver sees them.
        const target = move.placement ? [{ r: move.placement.r, c: move.placement.c }] : [];
        const cands = getGridCandidates(board);
        const notes: Record<string, number[]> = {};
        for (const { r, c } of [...move.triggers, ...move.eliminations, ...target]) {
          notes[`${r}-${c}`] = cands[r]![c]!.filter(
            (n) => !elims.some((e) => e.r === r && e.c === c && e.num === n),
          );
        }
        const cells = (list: { r: number; c: number }[]) => {
          const seen = new Set<string>();
          return list
            .filter(({ r, c }) => !seen.has(`${r}-${c}`) && seen.add(`${r}-${c}`))
            .map(({ r, c }) => ({ r, c }));
        };
        return {
          board: board.map((r) => [...r]),
          notes,
          target,
          trigger: cells(move.triggers),
          elimination: cells(move.eliminations),
          digits: move.digits,
          placement: move.placement ?? null,
        };
      }
      if (move.placement) board[move.placement.r]![move.placement.c] = move.placement.num;
      else elims.push(...move.eliminations);
    }
  }
  return null;
}

// Leaf objects and arrays on one line, like the hand-formatted file; oxfmt wraps what's too long.
const compact = (json: string) =>
  json
    .replace(
      /\{\s*([^{}[\]]*?)\s*\}/g,
      (_, body: string) => `{ ${body.replace(/\s*\n\s*/g, " ")} }`,
    )
    .replace(/\[\s*([^{}[\]]*?)\s*\]/g, (_, body: string) => `[${body.replace(/\s*\n\s*/g, " ")}]`);

describe.skipIf(!process.env.HARVEST)("academy harvest", () => {
  it("writes an example for every technique that lacks one", () => {
    const examples = { ...ACADEMY_EXAMPLES };
    for (const id of WANTED) {
      if (examples[id]) continue;
      const ex = harvest(id);
      expect([id, ex !== null]).toEqual([id, true]);
      examples[id] = ex!;
    }
    const header = `// AUTO-GENERATED by tests/academyHarvest.test.ts — real solver states where each
// technique is the next logical move. Candidates are derived from the actual
// board state, so every pencil mark shown is genuinely valid. Do not hand-edit;
// run \`HARVEST=1 pnpm test academyHarvest\` to add examples for new techniques.
import type { TechniqueId } from "./sudokuGrader";

export interface AcademyExample {
  board: number[][];
  notes: Record<string, number[]>;
  target: { r: number; c: number }[];
  trigger: { r: number; c: number }[];
  elimination: { r: number; c: number }[];
  digits: number[];
  placement: { r: number; c: number; num: number } | null;
}

export const ACADEMY_EXAMPLES: Partial<Record<TechniqueId, AcademyExample>> = `;
    writeFileSync(
      new URL("../utils/academyExamples.ts", import.meta.url),
      `${header}${compact(JSON.stringify(examples, null, 2))};\n`,
    );
  });
});
